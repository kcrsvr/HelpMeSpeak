#!/usr/bin/env node
// ============================================================
// generate-voice-pack.mjs
//
// Option B — generate a bundled child-voice pack from a PRE-MADE (not cloned)
// child voice, run ONCE at build time. It:
//   1. Collects the app's fixed phrases: A–Z letters, every seed word, "Welcome".
//   2. Calls a text-to-speech provider (ElevenLabs by default) for each phrase.
//   3. Writes mp3 clips to src/assets/voice/clips/.
//   4. Regenerates src/assets/voice/index.ts so the app plays these clips
//      instead of on-device TTS.
//
// The app itself never contains an API key or makes TTS calls at runtime —
// this script is the only thing that talks to the provider, on your machine.
//
// ── LEGAL / LICENSING ────────────────────────────────────────────────
//   • Use a PRE-MADE child voice provided by the service. Do NOT clone a real
//     child's voice.
//   • You must be on a plan that grants COMMERCIAL / distribution rights for
//     the generated audio (e.g. ElevenLabs Starter+). Free tiers usually do
//     NOT permit shipping the audio in a distributed app.
//   • Keep proof of your license.
//
// ── USAGE ────────────────────────────────────────────────────────────
//   ELEVENLABS_API_KEY=sk_xxx \
//   ELEVENLABS_VOICE_ID=<a pre-made kid voice id> \
//   node scripts/generate-voice-pack.mjs
//
// Optional:
//   VOICE_MODEL=eleven_multilingual_v2   (default)
//   DRY_RUN=1                            (list phrases, make no API calls)
// ============================================================

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const CLIPS_DIR = path.join(ROOT, "src/assets/voice/clips");
const REGISTRY = path.join(ROOT, "src/assets/voice/index.ts");
const SEED = path.join(ROOT, "src/data/seed.ts");

// ---- lookup key + filename helpers (must match src/assets/voice/index.ts) ----
function voiceKey(text) {
  return text.trim().toLowerCase().replace(/[^a-z0-9\s]/g, "").replace(/\s+/g, "_");
}

// ---- 1. collect the fixed phrase list ----
function collectPhrases() {
  const phrases = new Set();

  // A–Z letters
  for (let c = 97; c <= 122; c++) phrases.add(String.fromCharCode(c));

  // "Welcome" greeting
  phrases.add("Welcome");

  // Every seed word, parsed straight from seed.ts so this stays in sync.
  const seedSrc = fs.readFileSync(SEED, "utf8");
  const re = /word:\s*"([^"]+)"/g;
  let m;
  while ((m = re.exec(seedSrc)) !== null) phrases.add(m[1]);

  return [...phrases];
}

// ---- 2. ElevenLabs TTS call ----
async function synthesizeElevenLabs(text, apiKey, voiceId, model) {
  const url = `https://api.elevenlabs.io/v1/text-to-speech/${voiceId}`;
  const res = await fetch(url, {
    method: "POST",
    headers: {
      "xi-api-key": apiKey,
      "Content-Type": "application/json",
      Accept: "audio/mpeg",
    },
    body: JSON.stringify({
      text,
      model_id: model,
      voice_settings: { stability: 0.5, similarity_boost: 0.75 },
    }),
  });
  if (!res.ok) {
    throw new Error(`ElevenLabs ${res.status}: ${await res.text()}`);
  }
  return Buffer.from(await res.arrayBuffer());
}

// ---- 3. write the registry file ----
function writeRegistry(entries) {
  // entries: [{ key, file }]
  const lines = entries
    .sort((a, b) => a.key.localeCompare(b.key))
    .map((e) => `  ${JSON.stringify(e.key)}: require("./clips/${e.file}"),`)
    .join("\n");

  const content = `// AUTO-GENERATED by scripts/generate-voice-pack.mjs — do not edit by hand.
// Regenerate after changing the seed words or the voice.

export const VOICE_PACK: Record<string, number> = {
${lines}
};

export function voiceKey(text: string): string {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9\\s]/g, "")
    .replace(/\\s+/g, "_");
}

export function voiceClip(text: string): number | null {
  const key = voiceKey(text);
  return VOICE_PACK[key] ?? null;
}

export function hasVoicePack(): boolean {
  return Object.keys(VOICE_PACK).length > 0;
}
`;
  fs.writeFileSync(REGISTRY, content, "utf8");
}

// ---- main ----
async function main() {
  const phrases = collectPhrases();
  console.log(`Collected ${phrases.length} phrases.`);

  if (process.env.DRY_RUN) {
    console.log(phrases.join(", "));
    console.log("\nDRY_RUN set — no audio generated.");
    return;
  }

  const apiKey = process.env.ELEVENLABS_API_KEY;
  const voiceId = process.env.ELEVENLABS_VOICE_ID;
  const model = process.env.VOICE_MODEL || "eleven_multilingual_v2";
  if (!apiKey || !voiceId) {
    console.error(
      "Missing ELEVENLABS_API_KEY or ELEVENLABS_VOICE_ID.\n" +
        "Pick a PRE-MADE kid voice id (not a clone) and use a commercial plan.\n" +
        "Run with DRY_RUN=1 to preview the phrase list without any API calls."
    );
    process.exit(1);
  }

  fs.mkdirSync(CLIPS_DIR, { recursive: true });
  const entries = [];

  for (const phrase of phrases) {
    const key = voiceKey(phrase);
    const file = `${key}.mp3`;
    const dest = path.join(CLIPS_DIR, file);
    process.stdout.write(`  ${phrase} -> ${file} ... `);
    try {
      const audio = await synthesizeElevenLabs(phrase, apiKey, voiceId, model);
      fs.writeFileSync(dest, audio);
      entries.push({ key, file });
      console.log("ok");
    } catch (e) {
      console.log("FAILED");
      console.error(`    ${e.message}`);
    }
    // be gentle with rate limits
    await new Promise((r) => setTimeout(r, 250));
  }

  if (entries.length === 0) {
    console.error("No clips generated; leaving registry unchanged.");
    process.exit(1);
  }

  writeRegistry(entries);
  console.log(`\nWrote ${entries.length} clips to src/assets/voice/clips/`);
  console.log("Regenerated src/assets/voice/index.ts");
  console.log("Rebuild the app to hear the new voice pack.");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
